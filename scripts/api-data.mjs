// Bundles the core registries, their schemas and the sample dataset into one module the API Worker imports.
// A Worker has no file system, so the JSON files become static imports; nothing here names a registry or a file:
// the directories are listed. The output is generated, never edited; `--check` exits 1 when it is stale.
//   node scripts/api-data.mjs            write workers/api/src/data.generated.js
//   node scripts/api-data.mjs --check    exit 1 when the file differs from what the directories give
import { readdirSync, readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const out = new URL("workers/api/src/data.generated.js", root);
const groups = [
  ["registry", "vendor/core/registry", "registries"],
  ["schema", "vendor/core/schemas", "schemas"],
  ["sample", "vendor/core/sample", "samples"],
];
const strip = (file) => file.replace(/\.schema\.json$|\.json$/, "");
const ident = (group, name) => `${group}_${name.replace(/[^A-Za-z0-9]/g, "_")}`;

const lines = ["// Generated by scripts/api-data.mjs from vendor/core: do not edit by hand (node scripts/api-data.mjs)."];
const maps = {};
for (const [group, dir] of groups) {
  maps[group] = [];
  for (const file of readdirSync(new URL(`${dir}/`, root)).filter((f) => f.endsWith(".json")).sort()) {
    if (group === "schema" && !file.endsWith(".schema.json")) continue;
    const name = strip(file);
    lines.push(`import ${ident(group, name)} from "../../../${dir}/${file}" with { type: "json" };`);
    maps[group].push([name, ident(group, name)]);
  }
}
for (const [group, , plural] of groups) {
  lines.push(`export const ${plural} = {`, ...maps[group].map(([name, id]) => `  ${JSON.stringify(name)}: ${id},`), "};");
}
const text = `${lines.join("\n")}\n`;

if (process.argv.includes("--check")) {
  let have = "";
  try { have = readFileSync(out, "utf8"); } catch { /* a missing file means the output is stale */ }
  if (have !== text) { console.error("stale: workers/api/src/data.generated.js (run node scripts/api-data.mjs)"); process.exit(1); }
  console.log("ok: workers/api/src/data.generated.js is fresh");
} else {
  writeFileSync(out, text);
  console.log("wrote workers/api/src/data.generated.js");
}
